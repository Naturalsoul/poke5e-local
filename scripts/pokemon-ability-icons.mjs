export const POKEMON_ABILITY_ICON_PATHS = Object.values(ICONS).map(icon => `icons/${icon}.webp`);

const MODULE_ID = "poke5e-local";
const DEFAULT_ABILITY_ICON = "icons/svg/aura.svg";

// Pokémon made before Ability icons existed swap the default aura for their icon; icons changed by hand are kept.
export async function refreshPokemonAbilityIcons(actor) {
  const updates = actor.items
    .filter(item => item.getFlag(MODULE_ID, "kind") === "ability" && item.img === DEFAULT_ABILITY_ICON)
    .map(item => ({ _id: item.id, img: pokemonAbilityIcon(item.getFlag(MODULE_ID, "sourceId")) }))
    .filter(update => update.img);
  if (updates.length) {await actor.updateEmbeddedDocuments("Item", updates);}
}

export function registerPokemonAbilityIcons() {
  Hooks.once("ready", async () => {
    if (!game.user.isGM || (game.users.activeGM && game.users.activeGM.id !== game.user.id)) {return;}
    for (const actor of game.actors) {
      try {
        await refreshPokemonAbilityIcons(actor);
      } catch (error) {
        console.error(`[${MODULE_ID}] Ability icons for ${actor.name}`, error);
      }
    }
  });
}
